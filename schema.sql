-- ===== 01_core.sql =====
-- Core shared tables used by all three modules (booking, records, pharmacy).
CREATE TABLE department (
  department_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(100) NOT NULL UNIQUE,
  location      VARCHAR(100)
);

CREATE TABLE staff (
  staff_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name    VARCHAR(100) NOT NULL,
  last_name     VARCHAR(100) NOT NULL,
  role          TEXT NOT NULL CHECK (role IN ('doctor','pharmacist','nurse','technician')),
  department_id INT REFERENCES department(department_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  license_no    VARCHAR(50) UNIQUE,
  phone         CHAR(10) CONSTRAINT chk_staff_phone CHECK (phone ~ '^[0-9]{10}$'),
  email         VARCHAR(100) UNIQUE
);

CREATE TABLE patient (
  patient_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hn          VARCHAR(20) NOT NULL UNIQUE,
  national_id VARCHAR(13) NOT NULL UNIQUE,
  first_name  VARCHAR(100) NOT NULL,
  last_name   VARCHAR(100) NOT NULL,
  birth_date  DATE,
  gender      CHAR(1) CHECK (gender IN ('M','F','O')),
  phone       CHAR(10) CONSTRAINT chk_patient_phone CHECK (phone ~ '^[0-9]{10}$'),
  email       VARCHAR(100) UNIQUE,
  address     VARCHAR(255),
  blood_type  VARCHAR(5),
  allergy_note TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Links a Supabase Auth user to exactly one domain identity (or none for admin).
CREATE TABLE profiles (
  user_id    UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  role       TEXT NOT NULL CHECK (role IN ('admin','doctor','pharmacist','nurse','patient')),
  patient_id INT REFERENCES patient(patient_id) ON DELETE CASCADE,
  staff_id   INT REFERENCES staff(staff_id) ON DELETE CASCADE,
  CONSTRAINT chk_profile_identity CHECK (
       (role = 'admin'   AND patient_id IS NULL AND staff_id IS NULL)
    OR (role = 'patient' AND patient_id IS NOT NULL AND staff_id IS NULL)
    OR (role IN ('doctor','pharmacist','nurse') AND staff_id IS NOT NULL AND patient_id IS NULL))
);

-- Only users an admin has linked to a non-patient profile may use the app (open sign-up must not grant access).
-- Defined here (not in 06_rls.sql) because the views in 05_views.sql call it.
CREATE FUNCTION is_app_user() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS
$$ SELECT EXISTS (SELECT 1 FROM profiles WHERE user_id = auth.uid() AND role <> 'patient') $$;
REVOKE ALL ON FUNCTION is_app_user() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION is_app_user() TO authenticated, service_role;

-- Patient accounts: the patient this user was linked to by an admin (NULL for staff, admins and unlinked accounts).
-- Patients see and change only their own rows (policies and guards in 06_rls.sql).
CREATE FUNCTION my_patient_id() RETURNS int LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS
$$ SELECT patient_id FROM profiles WHERE user_id = auth.uid() AND role = 'patient' $$;
REVOKE ALL ON FUNCTION my_patient_id() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION my_patient_id() TO authenticated, service_role;

-- TRUE when no signed-in user is attached to the request: the SQL editor, the service_role key, or the chat RPC called
-- without a user. Security definer so roles without USAGE on schema auth (chat_reader) can call it inside the views.
CREATE FUNCTION no_signed_in_user() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS
$$ SELECT auth.uid() IS NULL $$;
REVOKE ALL ON FUNCTION no_signed_in_user() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION no_signed_in_user() TO authenticated, service_role;

-- ===== 02_records.sql =====
-- Medical records module (member C): rooms/beds, visits (hub), admissions, diagnosis, labs, insurance, charges.
CREATE TABLE room (
  room_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_no       VARCHAR(20) NOT NULL,
  room_type     VARCHAR(50),
  department_id INT REFERENCES department(department_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  capacity      INT CHECK (capacity > 0)
);
CREATE TABLE bed (
  bed_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id INT NOT NULL REFERENCES room(room_id) ON DELETE CASCADE,
  bed_no  VARCHAR(20) NOT NULL,
  status  VARCHAR(20) NOT NULL DEFAULT 'Available' CHECK (status IN ('Available','Occupied','Maintenance')),
  UNIQUE (room_id, bed_no)
);
CREATE TABLE visit (
  visit_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id     INT NOT NULL REFERENCES patient(patient_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  staff_id       INT REFERENCES staff(staff_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  visit_type     VARCHAR(3) NOT NULL CHECK (visit_type IN ('OPD','IPD','ER')),
  admit_date     TIMESTAMPTZ NOT NULL,
  discharge_date TIMESTAMPTZ,
  status         VARCHAR(30),
  CONSTRAINT chk_visit_dates CHECK (discharge_date IS NULL OR discharge_date >= admit_date)
);
CREATE INDEX idx_visit_type_date ON visit (visit_type, admit_date);
CREATE INDEX idx_visit_patient ON visit (patient_id);
CREATE TABLE admission (
  admission_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id      INT NOT NULL REFERENCES visit(visit_id) ON DELETE CASCADE,
  bed_id        INT NOT NULL REFERENCES bed(bed_id) ON DELETE RESTRICT,
  assigned_date TIMESTAMPTZ NOT NULL,
  released_date TIMESTAMPTZ,
  CONSTRAINT chk_admission_dates CHECK (released_date IS NULL OR released_date >= assigned_date)
);
CREATE TABLE diagnosis (
  diagnosis_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id       INT NOT NULL REFERENCES visit(visit_id) ON DELETE CASCADE,
  icd_code       VARCHAR(20),
  description    TEXT,
  diagnosed_date TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE lab_result (
  lab_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id     INT NOT NULL REFERENCES visit(visit_id) ON DELETE CASCADE,
  test_name    VARCHAR(150) NOT NULL,
  result_value VARCHAR(255),
  test_date    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE insurance_coverage (
  insurance_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id    INT NOT NULL REFERENCES patient(patient_id) ON DELETE CASCADE,
  provider_name VARCHAR(150),
  policy_no     VARCHAR(50),
  coverage_type VARCHAR(50)
);
CREATE TABLE daily_charge (
  charge_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id         INT NOT NULL REFERENCES visit(visit_id) ON DELETE CASCADE,
  charge_date      DATE NOT NULL,
  item_description VARCHAR(255),
  amount           NUMERIC(12,2) NOT NULL CHECK (amount >= 0)
);

-- ===== 03_booking.sql =====
-- Booking module (member A): appointments and patient feedback.
CREATE TABLE booking (
  booking_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id   INT NOT NULL REFERENCES patient(patient_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  staff_id     INT NOT NULL REFERENCES staff(staff_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  visit_id     INT REFERENCES visit(visit_id) ON UPDATE CASCADE ON DELETE SET NULL,
  booking_date DATE NOT NULL,
  booking_time TIME NOT NULL,
  queue_no     SMALLINT NOT NULL CHECK (queue_no > 0),
  symptom      TEXT,
  status       VARCHAR(10) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','completed','cancelled')),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_doctor_day_queue UNIQUE (staff_id, booking_date, queue_no),
  CONSTRAINT uq_doctor_day_time  UNIQUE (staff_id, booking_date, booking_time)
);
CREATE INDEX idx_bookings_patient ON booking (patient_id);
CREATE INDEX idx_date_status ON booking (booking_date, status);

-- security definer: a patient booking a queue cannot read staff (RLS), but the check must still see the doctor
CREATE FUNCTION trg_booking_staff_is_doctor() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF (SELECT role FROM staff WHERE staff_id = NEW.staff_id) IS DISTINCT FROM 'doctor' THEN
    RAISE EXCEPTION 'booking.staff_id must reference a doctor' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER booking_staff_is_doctor BEFORE INSERT OR UPDATE OF staff_id ON booking
  FOR EACH ROW EXECUTE FUNCTION trg_booking_staff_is_doctor();

CREATE TABLE feedback (
