-- AIE313 Hospital Information System: merged schema (PostgreSQL 15+ / Supabase)
-- Order: core -> records -> booking -> pharmacy -> views -> RLS. Run once on an empty project.

-- ===== 00_extensions.sql =====
-- No extra extensions required (gen_random_uuid is built in on PG13+).

-- ===== 01_core.sql =====
-- Core shared tables used by all three modules (booking, records, pharmacy).
CREATE TABLE department (
  department_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(100) NOT NULL UNIQUE,
  location      VARCHAR(100)
);

CREATE TABLE staff (
  staff_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name    VARCHAR(100) NOT NULL,
  last_name     VARCHAR(100) NOT NULL,
  role          TEXT NOT NULL CHECK (role IN ('doctor','pharmacist','nurse','technician')),
  department_id INT REFERENCES department(department_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  license_no    VARCHAR(50) UNIQUE,
  phone         CHAR(10) CONSTRAINT chk_staff_phone CHECK (phone ~ '^[0-9]{10}$'),
  email         VARCHAR(100) UNIQUE
);

CREATE TABLE patient (
  patient_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hn          VARCHAR(20) NOT NULL UNIQUE,
  national_id VARCHAR(13) NOT NULL UNIQUE,
  first_name  VARCHAR(100) NOT NULL,
  last_name   VARCHAR(100) NOT NULL,
  birth_date  DATE,
  gender      CHAR(1) CHECK (gender IN ('M','F','O')),
  phone       CHAR(10) CONSTRAINT chk_patient_phone CHECK (phone ~ '^[0-9]{10}$'),
  email       VARCHAR(100) UNIQUE,
  address     VARCHAR(255),
  blood_type  VARCHAR(5),
  allergy_note TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Links a Supabase Auth user to exactly one domain identity (or none for admin).
CREATE TABLE profiles (
  user_id    UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  role       TEXT NOT NULL CHECK (role IN ('admin','doctor','pharmacist','nurse','patient')),
  patient_id INT REFERENCES patient(patient_id) ON DELETE CASCADE,
  staff_id   INT REFERENCES staff(staff_id) ON DELETE CASCADE,
  CONSTRAINT chk_profile_identity CHECK (
       (role = 'admin'   AND patient_id IS NULL AND staff_id IS NULL)
    OR (role = 'patient' AND patient_id IS NOT NULL AND staff_id IS NULL)
    OR (role IN ('doctor','pharmacist','nurse') AND staff_id IS NOT NULL AND patient_id IS NULL))
);

-- ===== 02_records.sql =====
-- Medical records module (member C): rooms/beds, visits (hub), admissions, diagnosis, labs, insurance, charges.
CREATE TABLE room (
  room_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_no       VARCHAR(20) NOT NULL,
  room_type     VARCHAR(50),
  department_id INT REFERENCES department(department_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  capacity      INT CHECK (capacity > 0)
);
CREATE TABLE bed (
  bed_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id INT NOT NULL REFERENCES room(room_id) ON DELETE CASCADE,
  bed_no  VARCHAR(20) NOT NULL,
  status  VARCHAR(20) NOT NULL DEFAULT 'Available' CHECK (status IN ('Available','Occupied','Maintenance')),
  UNIQUE (room_id, bed_no)
);
CREATE TABLE visit (
  visit_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id     INT NOT NULL REFERENCES patient(patient_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  staff_id       INT REFERENCES staff(staff_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  visit_type     VARCHAR(3) NOT NULL CHECK (visit_type IN ('OPD','IPD','ER')),
  admit_date     TIMESTAMPTZ NOT NULL,
  discharge_date TIMESTAMPTZ,
  status         VARCHAR(30),
  CONSTRAINT chk_visit_dates CHECK (discharge_date IS NULL OR discharge_date >= admit_date)
);
CREATE INDEX idx_visit_type_date ON visit (visit_type, admit_date);
CREATE INDEX idx_visit_patient ON visit (patient_id);
CREATE TABLE admission (
  admission_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id      INT NOT NULL REFERENCES visit(visit_id) ON DELETE CASCADE,
  bed_id        INT NOT NULL REFERENCES bed(bed_id) ON DELETE RESTRICT,
  assigned_date TIMESTAMPTZ NOT NULL,
  released_date TIMESTAMPTZ,
  CONSTRAINT chk_admission_dates CHECK (released_date IS NULL OR released_date >= assigned_date)
);
CREATE TABLE diagnosis (
  diagnosis_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id       INT NOT NULL REFERENCES visit(visit_id) ON DELETE CASCADE,
  icd_code       VARCHAR(20),
  description    TEXT,
  diagnosed_date TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE lab_result (
  lab_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id     INT NOT NULL REFERENCES visit(visit_id) ON DELETE CASCADE,
  test_name    VARCHAR(150) NOT NULL,
  result_value VARCHAR(255),
  test_date    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE insurance_coverage (
  insurance_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id    INT NOT NULL REFERENCES patient(patient_id) ON DELETE CASCADE,
  provider_name VARCHAR(150),
  policy_no     VARCHAR(50),
  coverage_type VARCHAR(50)
);
CREATE TABLE daily_charge (
  charge_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id         INT NOT NULL REFERENCES visit(visit_id) ON DELETE CASCADE,
  charge_date      DATE NOT NULL,
  item_description VARCHAR(255),
  amount           NUMERIC(12,2) NOT NULL CHECK (amount >= 0)
);

-- ===== 03_booking.sql =====
-- Booking module (member A): appointments and patient feedback.
CREATE TABLE booking (
  booking_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id   INT NOT NULL REFERENCES patient(patient_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  staff_id     INT NOT NULL REFERENCES staff(staff_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  visit_id     INT REFERENCES visit(visit_id) ON UPDATE CASCADE ON DELETE SET NULL,
  booking_date DATE NOT NULL,
  booking_time TIME NOT NULL,
  queue_no     SMALLINT NOT NULL CHECK (queue_no > 0),
  symptom      TEXT,
  status       VARCHAR(10) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','completed','cancelled')),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_doctor_day_queue UNIQUE (staff_id, booking_date, queue_no),
  CONSTRAINT uq_doctor_day_time  UNIQUE (staff_id, booking_date, booking_time)
);
CREATE INDEX idx_bookings_patient ON booking (patient_id);
CREATE INDEX idx_date_status ON booking (booking_date, status);

CREATE FUNCTION trg_booking_staff_is_doctor() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (SELECT role FROM staff WHERE staff_id = NEW.staff_id) IS DISTINCT FROM 'doctor' THEN
    RAISE EXCEPTION 'booking.staff_id must reference a doctor' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER booking_staff_is_doctor BEFORE INSERT OR UPDATE OF staff_id ON booking
  FOR EACH ROW EXECUTE FUNCTION trg_booking_staff_is_doctor();

CREATE TABLE feedback (
  feedback_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id  INT NOT NULL REFERENCES patient(patient_id) ON UPDATE CASCADE ON DELETE CASCADE,
  booking_id  INT REFERENCES booking(booking_id) ON UPDATE CASCADE ON DELETE SET NULL,
  message     TEXT NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ===== 04_pharmacy.sql =====
-- Pharmacy / dispensing module (member B): formulary, lots, prescriptions, dispensing, stock, allergies.
CREATE TABLE drug (
  drug_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  generic_name      VARCHAR(200) NOT NULL,
  trade_name        VARCHAR(200) NOT NULL,
  dosage_form       VARCHAR(50) NOT NULL,
  strength          VARCHAR(50) NOT NULL,
  unit              VARCHAR(30) NOT NULL,
  is_high_alert     BOOLEAN NOT NULL DEFAULT FALSE,
  storage_condition VARCHAR(100) NOT NULL DEFAULT 'Room Temperature (15-30 C)'
);
CREATE TABLE drug_lot (
  lot_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drug_id          INT NOT NULL REFERENCES drug(drug_id) ON DELETE RESTRICT,
  lot_number       VARCHAR(50) NOT NULL,
  manufacture_date DATE NOT NULL,
  expiry_date      DATE NOT NULL,
  cost_per_unit    NUMERIC(10,2) NOT NULL CHECK (cost_per_unit >= 0),
  initial_quantity INT NOT NULL CHECK (initial_quantity >= 0),
  CONSTRAINT uq_drug_lot UNIQUE (drug_id, lot_number),
  CONSTRAINT chk_lot_dates CHECK (expiry_date > manufacture_date)
);
CREATE INDEX idx_drug_lot_fefo ON drug_lot (drug_id, expiry_date ASC);

CREATE TABLE prescription (
  prescription_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id          INT NOT NULL REFERENCES visit(visit_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  staff_id          INT NOT NULL REFERENCES staff(staff_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  prescription_date TIMESTAMPTZ NOT NULL DEFAULT now(),
  status            VARCHAR(20) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Screened','Dispensed','Cancelled')),
  total_price       NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (total_price >= 0)
);
CREATE INDEX idx_prescription_pending ON prescription (prescription_date ASC) WHERE status = 'Pending';

CREATE TABLE prescription_item (
  item_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prescription_id INT NOT NULL REFERENCES prescription(prescription_id) ON DELETE CASCADE,
  drug_id         INT NOT NULL REFERENCES drug(drug_id),
  dosage          VARCHAR(50) NOT NULL,
  route           VARCHAR(50) NOT NULL,
  frequency       VARCHAR(50) NOT NULL,
  quantity        INT NOT NULL CHECK (quantity > 0),
  duration_days   INT NOT NULL CHECK (duration_days > 0),
  instruction     TEXT
);

CREATE TABLE dispense_record (
  dispense_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id            INT NOT NULL REFERENCES prescription_item(item_id) ON DELETE RESTRICT,
  staff_id           INT NOT NULL REFERENCES staff(staff_id),
  lot_id             INT NOT NULL REFERENCES drug_lot(lot_id),
  dispense_date      TIMESTAMPTZ NOT NULL DEFAULT now(),
  dispensed_quantity INT NOT NULL CHECK (dispensed_quantity > 0),
  status_code        CHAR(2) NOT NULL DEFAULT 'DP' CHECK (status_code IN ('DP','VF','CN'))
);
CREATE INDEX idx_dispense_item_staff ON dispense_record (item_id, staff_id);

CREATE FUNCTION trg_dispense_staff_is_pharmacist() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (SELECT role FROM staff WHERE staff_id = NEW.staff_id) IS DISTINCT FROM 'pharmacist' THEN
    RAISE EXCEPTION 'dispense_record.staff_id must reference a pharmacist' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER dispense_staff_is_pharmacist BEFORE INSERT OR UPDATE OF staff_id ON dispense_record
  FOR EACH ROW EXECUTE FUNCTION trg_dispense_staff_is_pharmacist();

CREATE TABLE inventory (
  inventory_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drug_id          INT NOT NULL REFERENCES drug(drug_id),
  lot_id           INT NOT NULL REFERENCES drug_lot(lot_id),
  location         VARCHAR(50) NOT NULL,
  quantity_on_hand INT NOT NULL DEFAULT 0 CHECK (quantity_on_hand >= 0),
  reorder_point    INT NOT NULL DEFAULT 100 CHECK (reorder_point >= 0),
  last_updated     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_inventory_lookup ON inventory (drug_id, location, lot_id);

CREATE TABLE drug_allergy_record (
  allergy_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id       INT NOT NULL REFERENCES patient(patient_id) ON DELETE CASCADE,
  drug_id          INT NOT NULL REFERENCES drug(drug_id),
  reaction_details TEXT NOT NULL,
  severity         VARCHAR(20) CHECK (severity IN ('Mild','Moderate','Severe','Fatal')),
  recorded_date    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ===== 05_views.sql =====
-- 9 chat-visible views (owner-rights so chat_reader needs no table access); none expose national_id/phone/email/address/birth_date.
-- ===== Member A: booking =====
CREATE VIEW v_booking_queue_today AS
SELECT b.booking_id, b.queue_no, b.booking_time, p.hn, p.first_name AS patient_first_name,
       s.first_name || ' ' || s.last_name AS doctor_name, d.name AS department, b.symptom, b.status
FROM booking b
JOIN patient p ON p.patient_id = b.patient_id
JOIN staff s ON s.staff_id = b.staff_id
LEFT JOIN department d ON d.department_id = s.department_id
WHERE b.booking_date = CURRENT_DATE
ORDER BY s.staff_id, b.queue_no;

CREATE VIEW v_doctor_workload AS
SELECT s.staff_id, s.first_name || ' ' || s.last_name AS doctor_name, d.name AS department,
       b.status, COUNT(*) AS booking_count
FROM booking b
JOIN staff s ON s.staff_id = b.staff_id
LEFT JOIN department d ON d.department_id = s.department_id
GROUP BY s.staff_id, s.first_name, s.last_name, d.name, b.status;

CREATE VIEW v_feedback_summary AS
SELECT s.staff_id, s.first_name || ' ' || s.last_name AS doctor_name, d.name AS department,
       COUNT(f.feedback_id) AS feedback_count, MAX(f.created_at) AS latest_feedback_at
FROM feedback f
JOIN booking b ON b.booking_id = f.booking_id
JOIN staff s ON s.staff_id = b.staff_id
LEFT JOIN department d ON d.department_id = s.department_id
GROUP BY s.staff_id, s.first_name, s.last_name, d.name;

-- ===== Member C: records =====
CREATE VIEW v_bed_occupancy AS
SELECT r.room_id, r.room_no, r.room_type, d.name AS department,
       COUNT(b.bed_id) AS total_beds,
       COUNT(*) FILTER (WHERE b.status = 'Occupied') AS occupied_beds,
       COUNT(*) FILTER (WHERE b.status = 'Available') AS available_beds,
       ROUND(100.0 * COUNT(*) FILTER (WHERE b.status = 'Occupied') / NULLIF(COUNT(b.bed_id), 0), 1) AS occupancy_pct
FROM room r
LEFT JOIN bed b ON b.room_id = r.room_id
LEFT JOIN department d ON d.department_id = r.department_id
GROUP BY r.room_id, r.room_no, r.room_type, d.name;

CREATE VIEW v_visit_billing AS
SELECT v.visit_id, p.hn, p.first_name AS patient_first_name, v.visit_type, d.name AS department,
       to_char(c.charge_date, 'YYYY-MM') AS month, SUM(c.amount) AS total_amount, COUNT(*) AS charge_lines
FROM daily_charge c
JOIN visit v ON v.visit_id = c.visit_id
JOIN patient p ON p.patient_id = v.patient_id
LEFT JOIN staff s ON s.staff_id = v.staff_id
LEFT JOIN department d ON d.department_id = s.department_id
GROUP BY v.visit_id, p.hn, p.first_name, v.visit_type, d.name, to_char(c.charge_date, 'YYYY-MM');

CREATE VIEW v_top_diagnosis AS
SELECT icd_code, MAX(description) AS description, COUNT(*) AS case_count,
       RANK() OVER (ORDER BY COUNT(*) DESC) AS rank_no
FROM diagnosis
GROUP BY icd_code;

-- ===== Member B: pharmacy =====
CREATE VIEW v_pharmacist_screening_queue AS
SELECT pr.prescription_id, pr.status AS prescription_status, pr.prescription_date,
       p.hn, p.first_name AS patient_first_name, p.allergy_note,
       s.first_name || ' ' || s.last_name AS doctor_name,
       i.item_id, d.generic_name, d.trade_name, d.is_high_alert,
       i.dosage, i.route, i.frequency, i.quantity, i.duration_days
FROM prescription pr
JOIN visit v ON v.visit_id = pr.visit_id
JOIN patient p ON p.patient_id = v.patient_id
JOIN staff s ON s.staff_id = pr.staff_id
JOIN prescription_item i ON i.prescription_id = pr.prescription_id
JOIN drug d ON d.drug_id = i.drug_id
WHERE pr.status IN ('Pending', 'Screened');

CREATE VIEW v_inventory_stock_status AS
SELECT inv.inventory_id, d.generic_name, d.trade_name, l.lot_number, l.expiry_date, inv.location,
       inv.quantity_on_hand, inv.reorder_point,
       CASE WHEN inv.quantity_on_hand <= inv.reorder_point THEN 'REORDER_URGENT'
            WHEN l.expiry_date <= CURRENT_DATE + 90 THEN 'NEAR_EXPIRY'
            ELSE 'NORMAL' END AS stock_status
FROM inventory inv
JOIN drug d ON d.drug_id = inv.drug_id
JOIN drug_lot l ON l.lot_id = inv.lot_id;

CREATE VIEW v_drug_cost_summary AS
WITH presc AS (
  SELECT drug_id, COUNT(DISTINCT prescription_id) AS total_prescriptions, SUM(quantity) AS units_prescribed
  FROM prescription_item GROUP BY drug_id),
disp AS (
  SELECT i.drug_id, SUM(dr.dispensed_quantity) AS units_dispensed, SUM(dr.dispensed_quantity * l.cost_per_unit) AS dispensed_cost
  FROM dispense_record dr
  JOIN prescription_item i ON i.item_id = dr.item_id
  JOIN drug_lot l ON l.lot_id = dr.lot_id
  GROUP BY i.drug_id)
SELECT d.drug_id, d.generic_name, d.trade_name,
       COALESCE(presc.total_prescriptions, 0) AS total_prescriptions,
       COALESCE(presc.units_prescribed, 0) AS units_prescribed,
       COALESCE(disp.units_dispensed, 0) AS units_dispensed,
       COALESCE(disp.dispensed_cost, 0) AS dispensed_cost
FROM drug d
LEFT JOIN presc ON presc.drug_id = d.drug_id
LEFT JOIN disp ON disp.drug_id = d.drug_id;

-- ===== 06_rls.sql =====
-- Row Level Security: anon gets nothing; linked staff users (profiles) get the app tables and views.
-- (Fine-grained per-role policies can replace "authenticated_all" later.)
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon;
ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

-- Only users an admin has linked to a non-patient profile may use the app tables (open sign-up must not grant access).
CREATE FUNCTION is_app_user() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS
$$ SELECT EXISTS (SELECT 1 FROM profiles WHERE user_id = auth.uid() AND role <> 'patient') $$;
REVOKE ALL ON FUNCTION is_app_user() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION is_app_user() TO authenticated, service_role;

DO $$
DECLARE t text;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    IF t <> 'profiles' THEN
      EXECUTE format('CREATE POLICY authenticated_all ON %I FOR ALL TO authenticated USING (is_app_user()) WITH CHECK (is_app_user())', t);
    END IF;
  END LOOP;
END $$;

-- A signed-in user may only READ their own profile row (roles are assigned by an admin, never self-service).
CREATE POLICY own_profile ON profiles FOR SELECT TO authenticated
  USING (user_id = auth.uid());

-- ===== 07_chat_support.sql =====
-- Chat support: chat_logs (bonus), read-only role, and the RPC the Edge Function calls.
CREATE TABLE chat_logs (
  chat_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       UUID,
  question      TEXT NOT NULL,
  generated_sql TEXT,
  tool_name     TEXT,
  row_count     INT,
  error         TEXT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
REVOKE ALL ON chat_logs FROM anon;
GRANT SELECT, INSERT ON chat_logs TO authenticated;
ALTER TABLE chat_logs ENABLE ROW LEVEL SECURITY;
CREATE POLICY own_chat_logs_select ON chat_logs FOR SELECT TO authenticated USING (user_id = auth.uid());
CREATE POLICY own_chat_logs_insert ON chat_logs FOR INSERT TO authenticated WITH CHECK (user_id = auth.uid());

-- Read-only role used only inside run_readonly_query(): the 9 views, no base tables.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'chat_reader') THEN CREATE ROLE chat_reader NOLOGIN; END IF;
END $$;
GRANT USAGE ON SCHEMA public TO chat_reader;
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM chat_reader;
GRANT SELECT ON v_booking_queue_today, v_doctor_workload, v_feedback_summary, v_bed_occupancy, v_visit_billing,
                v_top_diagnosis, v_pharmacist_screening_queue, v_inventory_stock_status, v_drug_cost_summary TO chat_reader;

-- NOTE: statement_timeout cannot be (re)armed from inside a function, so long-running queries are prevented by
-- sqlGuard (no functions such as pg_sleep, forced LIMIT 100) and, optionally, a role-level timeout set once by an admin:
--   ALTER ROLE service_role SET statement_timeout = '10s';   -- PostgREST applies per-role settings per request
-- SECURITY DEFINER and OWNED BY chat_reader: the query runs with chat_reader's privileges (9 views only) and, because
-- Postgres forbids changing "role" inside a security-definer function, it cannot switch itself to service_role.
CREATE FUNCTION run_readonly_query(q text) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE result jsonb;
BEGIN
  EXECUTE format('SELECT coalesce(jsonb_agg(t), ''[]''::jsonb) FROM (%s) t', q) INTO result;
  RETURN result;
END $$;
ALTER FUNCTION run_readonly_query(text) OWNER TO chat_reader;
REVOKE ALL ON FUNCTION run_readonly_query(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION run_readonly_query(text) TO service_role;
