-- Medical records module (member C): rooms/beds, visits (hub), admissions, diagnosis, labs, insurance, charges.
CREATE TABLE room (
  room_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_no       VARCHAR(20) NOT NULL,
  room_type     VARCHAR(50),
  department_id INT REFERENCES department(department_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  capacity      INT CHECK (capacity > 0)
);
CREATE TABLE bed (
  bed_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id INT NOT NULL REFERENCES room(room_id) ON DELETE CASCADE,
  bed_no  VARCHAR(20) NOT NULL,
  status  VARCHAR(20) NOT NULL DEFAULT 'Available' CHECK (status IN ('Available','Occupied','Maintenance')),
  UNIQUE (room_id, bed_no)
);
CREATE TABLE visit (
  visit_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id     INT NOT NULL REFERENCES patient(patient_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  staff_id       INT REFERENCES staff(staff_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  visit_type     VARCHAR(3) NOT NULL CHECK (visit_type IN ('OPD','IPD','ER')),
  admit_date     TIMESTAMPTZ NOT NULL,
  discharge_date TIMESTAMPTZ,
  status         VARCHAR(30),
  CONSTRAINT chk_visit_dates CHECK (discharge_date IS NULL OR discharge_date >= admit_date)
);
CREATE INDEX idx_visit_type_date ON visit (visit_type, admit_date);
CREATE INDEX idx_visit_patient ON visit (patient_id);
CREATE TABLE admission (
  admission_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id      INT NOT NULL REFERENCES visit(visit_id) ON DELETE CASCADE,
  bed_id        INT NOT NULL REFERENCES bed(bed_id) ON DELETE RESTRICT,
  assigned_date TIMESTAMPTZ NOT NULL,
  released_date TIMESTAMPTZ,
  CONSTRAINT chk_admission_dates CHECK (released_date IS NULL OR released_date >= assigned_date)
);
CREATE TABLE diagnosis (
  diagnosis_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id       INT NOT NULL REFERENCES visit(visit_id) ON DELETE CASCADE,
  icd_code       VARCHAR(20),
  description    TEXT,
  diagnosed_date TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE lab_result (
  lab_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id     INT NOT NULL REFERENCES visit(visit_id) ON DELETE CASCADE,
  test_name    VARCHAR(150) NOT NULL,
  result_value VARCHAR(255),
  test_date    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE insurance_coverage (
  insurance_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id    INT NOT NULL REFERENCES patient(patient_id) ON DELETE CASCADE,
  provider_name VARCHAR(150),
  policy_no     VARCHAR(50),
  coverage_type VARCHAR(50)
);
CREATE TABLE daily_charge (
  charge_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visit_id         INT NOT NULL REFERENCES visit(visit_id) ON DELETE CASCADE,
  charge_date      DATE NOT NULL,
  item_description VARCHAR(255),
  amount           NUMERIC(12,2) NOT NULL CHECK (amount >= 0)
);
