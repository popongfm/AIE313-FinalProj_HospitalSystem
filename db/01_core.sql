-- Core shared tables used by all three modules (booking, records, pharmacy).
CREATE TABLE department (
  department_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR(100) NOT NULL UNIQUE,
  location      VARCHAR(100)
);

CREATE TABLE staff (
  staff_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name    VARCHAR(100) NOT NULL,
  last_name     VARCHAR(100) NOT NULL,
  role          TEXT NOT NULL CHECK (role IN ('doctor','pharmacist','nurse','technician')),
  department_id INT REFERENCES department(department_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  license_no    VARCHAR(50) UNIQUE,
  phone         CHAR(10) CONSTRAINT chk_staff_phone CHECK (phone ~ '^[0-9]{10}$'),
  email         VARCHAR(100) UNIQUE
);

CREATE TABLE patient (
  patient_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hn          VARCHAR(20) NOT NULL UNIQUE,
  national_id VARCHAR(13) NOT NULL UNIQUE,
  first_name  VARCHAR(100) NOT NULL,
  last_name   VARCHAR(100) NOT NULL,
  birth_date  DATE,
  gender      CHAR(1) CHECK (gender IN ('M','F','O')),
  phone       CHAR(10) CONSTRAINT chk_patient_phone CHECK (phone ~ '^[0-9]{10}$'),
  email       VARCHAR(100) UNIQUE,
  address     VARCHAR(255),
  blood_type  VARCHAR(5),
  allergy_note TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Links a Supabase Auth user to exactly one domain identity (or none for admin).
CREATE TABLE profiles (
  user_id    UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  role       TEXT NOT NULL CHECK (role IN ('admin','doctor','pharmacist','nurse','patient')),
  patient_id INT REFERENCES patient(patient_id) ON DELETE CASCADE,
  staff_id   INT REFERENCES staff(staff_id) ON DELETE CASCADE,
  CONSTRAINT chk_profile_identity CHECK (
       (role = 'admin'   AND patient_id IS NULL AND staff_id IS NULL)
    OR (role = 'patient' AND patient_id IS NOT NULL AND staff_id IS NULL)
    OR (role IN ('doctor','pharmacist','nurse') AND staff_id IS NOT NULL AND patient_id IS NULL))
);
