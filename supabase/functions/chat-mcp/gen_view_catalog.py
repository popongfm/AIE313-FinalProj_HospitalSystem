#!/usr/bin/env python3
"""Generate viewCatalog.ts (allowlisted views, columns, types) from the live database for the MCP tools.
Usage: python gen_view_catalog.py DBNAME > viewCatalog.ts   (PGHOST/PGPORT/PGUSER from env)"""
import subprocess, sys
db = sys.argv[1]
VIEWS = {
 'v_booking_queue_today': 'การจองคิวของวันนี้ (booking_time, queue_no, doctor_name, department, status)',
 'v_doctor_workload': 'จำนวนการจองต่อแพทย์ต่อสถานะ (status: pending/confirmed/completed/cancelled)',
 'v_feedback_summary': 'จำนวนข้อเสนอแนะต่อแพทย์',
 'v_bed_occupancy': 'อัตราการใช้เตียงต่อห้อง (occupancy_pct เป็นเปอร์เซ็นต์)',
 'v_visit_billing': 'ค่ารักษาต่อ visit ต่อเดือน (month รูปแบบ YYYY-MM, visit_type: OPD/IPD/ER)',
 'v_top_diagnosis': 'โรค (ICD) ที่พบมากที่สุด เรียงตาม rank_no',
 'v_pharmacist_screening_queue': 'รายการยาที่รอเภสัชกรตรวจสอบ (prescription_status: Pending/Screened)',
 'v_inventory_stock_status': 'สต็อกยาแต่ละ lot (stock_status: REORDER_URGENT/NEAR_EXPIRY/NORMAL)',
 'v_drug_cost_summary': 'สรุปการสั่ง/จ่ายยาและต้นทุนต่อยา',
}
def q(sql):
    r = subprocess.run(['psql', '-X', '-At', '-F', '|', '-d', db, '-c', sql], capture_output=True, text=True, check=True)
    return [l.split('|') for l in r.stdout.strip().splitlines() if l]
import json
cat = {}
for v, desc in VIEWS.items():
    cols = q("select column_name, udt_name from information_schema.columns where table_schema='public' and table_name='%s' order by ordinal_position" % v)
    cat[v] = {'description': desc, 'columns': [{'name': c, 'type': t} for c, t in cols]}
print('// GENERATED by gen_view_catalog.py from the database catalog. Do not edit by hand.')
print('export type ViewCatalog = Record<string, { description: string; columns: { name: string; type: string }[] }>;')
print('export const VIEW_CATALOG: ViewCatalog = %s;' % json.dumps(cat, ensure_ascii=False, indent=1))
